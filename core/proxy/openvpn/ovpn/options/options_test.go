func TestPKCS12Encodings(t *testing.T) {
	der := []byte("\x30\x82\x01\x0a some DER bytes \xff\xfe")
	for _, enc := range []string{
		base64.StdEncoding.EncodeToString(der),
		base64.RawStdEncoding.EncodeToString(der),
		wrap(base64.StdEncoding.EncodeToString(der), 8),
	} {
		o, err := Parse(block("pkcs12", enc+"\n"))
		if err != nil {
			t.Fatalf("%q: %v", enc, err)
		}
		if string(o.PKCS12) != string(der) {
			t.Errorf("%q decoded to %x", enc, o.PKCS12)
		}
	}
}

func wrap(s string, n int) string {
	var b strings.Builder
	for len(s) > n {
		b.WriteString(s[:n] + "\r\n")
		s = s[n:]
	}
	return b.String() + s
}

func TestSplitArgs(t *testing.T) {
	cases := []struct {
		in   string
		want []string
	}{
		{"", nil},
		{"   \t ", nil},
		{"remote a 1194", []string{"remote", "a", "1194"}},
		{"\tremote\ta  1194  ", []string{"remote", "a", "1194"}},
		{`remote "a b" 1`, []string{"remote", "a b", "1"}},
		{`remote 'a b' 1`, []string{"remote", "a b", "1"}},
		{`x "a\"b\\c"`, []string{"x", `a"b\c`}},
		{`x 'a\ b'`, []string{"x", `a\ b`}},
		{`x a\ b#c`, []string{"x", "a b#c"}},
		{`x a"b c"d`, []string{"x", `a"b`, `c"d`}},
		{`x "a"b 1`, []string{"x", "a", "b", "1"}},
		{`x "a b"c`, []string{"x", "a b", "c"}},
		{`x ""`, []string{"x", ""}},
		{`x '' y`, []string{"x", "", "y"}},
		{`x # comment "unclosed`, []string{"x"}},
		{`x ;comment`, []string{"x"}},
		{`x y;z`, []string{"x", "y;z"}},
		{`#x`, nil},
		{`ca C:\path\ca.crt`, []string{"ca", `C:\path\ca.crt`}},
		{`ca "C:\\path\\ca.crt"`, []string{"ca", `C:\path\ca.crt`}},
		{`x \"y`, []string{"x", `"y`}},
		{`x trailing\`, []string{"x", `trailing\`}},
	}
	for _, tc := range cases {
		got, err := splitArgs(tc.in)
		if err != nil {
			t.Errorf("splitArgs(%q): %v", tc.in, err)
			continue
		}
		if !reflect.DeepEqual(got, tc.want) {
			t.Errorf("splitArgs(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
	for _, in := range []string{`x "abc`, `x 'abc`, `x "a\"`} {
		if _, err := splitArgs(in); err == nil {
			t.Errorf("splitArgs(%q) succeeded", in)
		}
	}
}

