func TestParse(t *testing.T) {
	for _, tc := range parseCases {
		t.Run(tc.name, func(t *testing.T) {
			got, err := Parse(tc.text)
			if err != nil {
				t.Fatalf("Parse: %v", err)
			}
			want := defaults()
			tc.want(want)
			ignored := got.Ignored
			got.Ignored = nil
			if !reflect.DeepEqual(got, want) {
				t.Errorf("Parse mismatch\n got: %+v\nwant: %+v", got, want)
			}
			for _, n := range tc.ignored {
				if !slices.Contains(ignored, n) {
					t.Errorf("Ignored %q does not list %q", ignored, n)
				}
			}
			for _, n := range tc.notIgnored {
				if slices.Contains(ignored, n) {
					t.Errorf("Ignored %q lists %q", ignored, n)
				}
			}
			seen := map[string]bool{}
			for _, n := range ignored {
				if seen[n] {
					t.Errorf("Ignored lists %q twice", n)
				}
				seen[n] = true
			}
		})
	}
}

func TestParseErrors(t *testing.T) {
	cases := []struct {
		name, text  string
		unsupported bool
		contains    string
	}{
		{"dev tap", "remote r\ndev tap\n", true, "dev tap"},
		{"dev tap0", "remote r\ndev tap0\n", true, "dev tap"},
		{"dev-type tap", "remote r\ndev tun\ndev-type tap\n", true, "dev-type tap"},
		{"fragment", "remote r\nfragment 1300\n", true, "fragment"},
		{"secret", "remote r\nsecret static.key\n", true, "secret"},
		{"secret block", "remote r\n" + block("secret", staticKey), true, "secret"},
		{"http-proxy", "remote r\nhttp-proxy 10.0.0.1 8080\n", true, "http-proxy"},
		{"socks-proxy", "remote r\nsocks-proxy 10.0.0.1 1080\n", true, "socks-proxy"},
		{"pkcs11", "remote r\npkcs11-providers /usr/lib/p11.so\n", true, "pkcs11-providers"},
		{"pkcs11-id", "remote r\npkcs11-id 'x'\n", true, "pkcs11-id"},
		{"cryptoapicert", "remote r\ncryptoapicert \"SUBJ:Name\"\n", true, "cryptoapicert"},
		{"management-external-key", "remote r\nmanagement-external-key\n", true, "management-external-key"},
		{"tcp-server", "proto tcp-server\nremote r\n", true, "tcp-server"},
		{"remote tcp-server", "remote r 1194 tcp4-server\n", true, "tcp4-server"},
		{"mode server", "mode server\n", true, "mode server"},
		{"tls-server", "tls-server\n", true, "tls-server"},
		{"key-method 1", "key-method 1\n", true, "key-method 1"},
		{"tls-remote", "tls-remote server\n", true, "tls-remote"},
		{"unsupported inside connection", "<connection>\nremote r\nhttp-proxy p 8080\n</connection>\n", true, "http-proxy"},

		{"file without base dir", "remote r\nca ca.crt\n", false, "base directory"},
		{"config include without base dir", "config other.ovpn\n", false, "base directory"},
		{"inline without block", "remote r\ntls-auth [inline] 1\n", false, "no <tls-auth> block"},
		{"unclosed block", "remote r\n<ca>\n" + caPEM, false, "<ca> block without </ca>"},
		{"mismatched block", "remote r\n<ca>\n" + caPEM + "</cert>\n", false, "without </ca>"},
		{"unclosed double quote", "remote \"r 1194\n", false, "line 1: no closing double quote"},
		{"unclosed single quote", "remote r\nverify-x509-name 'x\n", false, "line 2: no closing single quote"},
		{"bad port", "remote r 70000\n", false, "bad port"},
		{"zero port", "remote r 0\n", false, "bad port"},
		{"bad global port", "port http\n", false, "bad port"},
		{"bad proto", "remote r 1194 sctp\n", false, "unknown protocol"},
		{"bad global proto", "proto quic\n", false, "unknown protocol"},
		{"remote without host", "remote\n", false, "missing argument"},
		{"remote with empty host", "remote \"\"\n", false, "empty host"},
		{"tls-auth and tls-crypt", "remote r\n" + block("tls-auth", staticKey) + block("tls-crypt", staticKey), false, "mutually exclusive"},
		{"tls-crypt and tls-crypt-v2", "remote r\n" + block("tls-crypt", staticKey) + block("tls-crypt-v2", cryptV2Key), false, "mutually exclusive"},
		{"key-direction 2", "remote r\nkey-direction 2\n", false, "0 or 1"},
		{"tls-auth direction 2", "remote r\ntls-auth [inline] 2\n" + block("tls-auth", staticKey), false, "0 or 1"},
		{"connection without remote", "remote r\n<connection>\nproto tcp\n</connection>\n", false, "line 2: <connection> block without remote"},
		{"nested connection", "<connection>\nremote r\n<connection>\nremote s\n</connection>\n</connection>\n", false, "inside <connection>"},
		{"bad fingerprint", "remote r\npeer-fingerprint AB:CD\n", false, "not a SHA-256 fingerprint"},
		{"bad fingerprint hex", "remote r\npeer-fingerprint " + strings.Repeat("zz", 32) + "\n", false, "not a SHA-256 fingerprint"},
		{"empty fingerprint block", "remote r\n" + block("peer-fingerprint", "# none\n"), false, "no fingerprint"},
		{"bad pkcs12", "remote r\n" + block("pkcs12", "not base64!\n"), false, "not base64"},
		{"tls-version-min", "tls-version-min 1.4\n", false, "unknown version"},
		{"tls-version-max", "tls-version-max 2\n", false, "unknown version"},
		{"verify-x509-name type", "verify-x509-name x cn\n", false, "unknown type"},
		{"remote-cert-tls client", "remote-cert-tls client\n", false, "only \"server\""},
		{"ns-cert-type client", "ns-cert-type client\n", false, "only \"server\""},
		{"pull-filter action", "pull-filter drop route\n", false, "unknown action"},
		{"pull-filter missing text", "pull-filter ignore\n", false, "needs an action and a text"},
		{"tun-mtu", "tun-mtu 20\n", false, "bad MTU"},
		{"ping", "ping -1\n", false, "bad number of seconds"},
		{"ping huge", "ping 99999999999999\n", false, "bad number of seconds"},
		{"keepalive one arg", "keepalive 10\n", false, "two arguments"},
		{"hand-window zero", "hand-window 0\n", false, "must be positive"},
		{"empty data-ciphers", "data-ciphers ::?\n", false, "empty cipher list"},
		{"missing cipher", "cipher\n", false, "missing argument"},
		{"explicit-exit-notify", "explicit-exit-notify x\n", false, "bad count"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			o, err := Parse(tc.text)
			if err == nil {
				t.Fatalf("Parse succeeded: %+v", o)
			}
			if got := errors.Is(err, ErrUnsupported); got != tc.unsupported {
				t.Errorf("errors.Is(%v, ErrUnsupported) = %v", err, got)
			}
			if !strings.Contains(err.Error(), tc.contains) {
				t.Errorf("error %q does not contain %q", err, tc.contains)
			}
			if !strings.HasPrefix(err.Error(), "options: ") {
				t.Errorf("error %q does not name the package", err)
			}
		})
	}
}

// TestParseErrorsHideSecrets checks that a failing line's secret arguments
// do not end up in the error.
func TestParseErrorsHideSecrets(t *testing.T) {
	_, err := Parse(block("auth-user-pass", "user\nhunter2\n") + "<connection>\nproto tcp\n</connection>\n")
	if err == nil || strings.Contains(err.Error(), "hunter2") {
		t.Fatalf("error %v", err)
	}
}

func TestParseWithBaseDir(t *testing.T) {
	dir := t.TempDir()
	der := []byte{0x30, 0x82, 0x00, 0x03, 0xde, 0xad, 0xbe}
	files := map[string]string{
		"ca.crt":         caPEM,
		"client.crt":     certPEM,
		"client.key":     keyPEM,
		"ta.key":         staticKey,
		"creds.txt":      "bob\r\npa ss\r\n",
		"client.p12":     string(der),
		"extra.pem":      caPEM,
		"sub/common.inc": "proto tcp\nport 1300\nconfig sub/more.inc\n",
		"sub/more.inc":   "remote included.example\n",
		"loop.inc":       "config loop.inc\n",
	}
	for name, content := range files {
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	text := "client\nremote r.example\nca ca.crt\ncert client.crt\nkey " + filepath.Join(dir, "client.key") +
		"\ntls-auth ta.key 1\nauth-user-pass creds.txt\npkcs12 client.p12\nextra-certs extra.pem\nconfig sub/common.inc\n"
	got, err := ParseWithBaseDir(text, dir)
	if err != nil {
		t.Fatal(err)
	}
	want := defaults()
	want.BaseDir = dir
	want.Remotes = []Remote{{"r.example", 1300, "tcp"}, {"included.example", 1300, "tcp"}}
	want.CA, want.Cert, want.Key, want.ExtraCerts = []byte(caPEM), []byte(certPEM), []byte(keyPEM), []byte(caPEM)
	want.TLSAuth, want.KeyDirection = []byte(staticKey), 1
	want.AuthUserPass, want.Username, want.Password = true, "bob", "pa ss"
	want.PKCS12 = der
	got.Ignored = nil
	if !reflect.DeepEqual(got, want) {
		t.Errorf("mismatch\n got: %+v\nwant: %+v", got, want)
	}

	// Plain Parse refuses the same file references.
	if _, err := Parse(text); err == nil || !strings.Contains(err.Error(), "base directory") {
		t.Errorf("Parse: %v", err)
	}
	for _, tc := range []struct{ text, contains string }{
		{"ca missing.crt\n", "missing.crt"},
		{"config loop.inc\n", "nested too deeply"},
		{"config sub/more.inc\nremote x\n<connection>\nremote y\n", "<connection> block without </connection>"},
	} {
		if _, err := ParseWithBaseDir(tc.text, dir); err == nil || !strings.Contains(err.Error(), tc.contains) {
			t.Errorf("ParseWithBaseDir(%q) = %v, want an error containing %q", tc.text, err, tc.contains)
		}
	}
	// A file reference written as [inline] still needs the block.
	if _, err := ParseWithBaseDir("ca [inline]\n", dir); err == nil {
		t.Error("ca [inline] without a block succeeded")
	}
	// An error in an included file names it.
	if err := os.WriteFile(filepath.Join(dir, "bad.inc"), []byte("\nfragment 1300\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	_, err = ParseWithBaseDir("config bad.inc\n", dir)
	if err == nil || !errors.Is(err, ErrUnsupported) || !strings.Contains(err.Error(), "bad.inc line 2") {
		t.Errorf("included error: %v", err)
	}
}

