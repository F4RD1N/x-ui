func block(name, content string) string { return "<" + name + ">\n" + content + "</" + name + ">\n" }

// mustFP decodes a fingerprint of the test material.
func mustFP(s string) [32]byte {
	fp, err := parseFingerprint(s)
	if err != nil {
		panic(err)
	}
	return fp
}

// defaults is what Parse returns for an empty config.
func defaults() *Options {
	return &Options{
		KeyDirection:   -1,
		DataCiphers:    []string{"AES-256-GCM", "AES-128-GCM", "CHACHA20-POLY1305"},
		Auth:           "SHA1",
		TunMTU:         1500,
		RenegSec:       time.Hour,
		HandWindow:     60 * time.Second,
		ConnectTimeout: 30 * time.Second,
	}
}

