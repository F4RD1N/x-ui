// The sysctl files x-ui writes, and the ones older versions wrote.
//
// SysctlFile sorts after the distribution defaults (50-*.conf) and before
// the files admins and other tools usually write (60-*, 90-*, 99-*,
// /etc/sysctl.conf): a value one of those sets, even after x-ui last wrote
// its file, wins at boot and on "sysctl --system". x-ui raises what is still
// below its target when it starts. OldSysctlFile is where it used to be,
// sorting after nearly everything; it is removed on the next apply.
const (
	SysctlFile       = "/etc/sysctl.d/51-x-ui.conf"
	OldSysctlFile    = "/etc/sysctl.d/99-x-ui.conf"
	LegacyBBRFile    = "/etc/sysctl.d/99-bbr-x-ui.conf"
	ModulesLoadFile  = "/etc/modules-load.d/x-ui.conf"
	ModprobeFile     = "/etc/modprobe.d/x-ui.conf"
	DropInDir        = "/etc/systemd/system/x-ui.service.d"
	DropInFile       = DropInDir + "/20-x-ui-tuning.conf"
	OpenRCConfFile   = "/etc/conf.d/x-ui-tune"
	StateDir         = "/var/lib/x-ui/tune"
	StateFile        = StateDir + "/state.json"
	TablesFile       = StateDir + "/rss-tables.json"
	BackupDir        = StateDir + "/backup"
	SwapFile         = "/var/lib/x-ui/swapfile"
	NICUnitFile      = "/etc/systemd/system/x-ui-nic.service"
	IRQBalanceDropIn = "/etc/systemd/system/irqbalance.service.d/90-x-ui.conf"
	IRQBalanceScript = StateDir + "/irqbalance-policy"
	IRQBalanceEnv    = StateDir + "/irqbalance.env"
	legacyDropInMark = "# Written by x-ui tune.sh"
)

// Header starts every file x-ui tune writes; revert recognises its files by
// it when the state file is lost.
const Header = `# Written by x-ui tune (github.com/F4RD1N/x-ui). Do not edit; re-generated by
# 'x-ui tune apply' and on every x-ui start, removed by 'x-ui tune revert'.
# x-ui only raises values and never lowers one set in another file: put your
# own values in a file of your own (or /etc/sysctl.conf); x-ui keeps them.
`

// sysctlNote follows the header in SysctlFile.
const sysctlNote = `# A file whose name sorts after this one's wins at boot. After changing a
# sysctl file, run 'x-ui tune apply' (or restart x-ui) so this one follows it.
`

var sysctlDirs = []string{"/etc/sysctl.d", "/run/sysctl.d", "/usr/local/lib/sysctl.d", "/usr/lib/sysctl.d", "/lib/sysctl.d"}

// Setting is one key as the boot sequence would leave it without x-ui.
type Setting struct {
	Value string
	File  string // the file that set it last
}

// kv is one assignment in a sysctl file.
type kv struct{ Key, Value string }

// normKey turns "net/ipv4/tcp_tw_reuse" into "net.ipv4.tcp_tw_reuse".
func normKey(k string) string {
	k = strings.TrimSpace(k)
	if strings.Contains(k, "/") {
		k = strings.ReplaceAll(strings.Trim(k, "/"), "/", ".")
	}
	return k
}

// normValue collapses whitespace, as the kernel prints multi-field values.
func normValue(v string) string { return strings.Join(strings.Fields(v), " ") }

// parseSysctl reads a sysctl.conf-format file: '#' and ';' comments, a
// leading '-' (ignore errors), whitespace around '='. Glob keys are skipped:
// none of them targets a key x-ui manages.
func parseSysctl(data string) []kv {
	var out []kv
	for _, l := range strings.Split(data, "\n") {
		l = strings.TrimSpace(l)
		if l == "" || l[0] == '#' || l[0] == ';' {
			continue
		}
		l = strings.TrimPrefix(l, "-")
		k, v, ok := strings.Cut(l, "=")
		if !ok {
			continue
		}
		k = normKey(k)
		if k == "" || strings.ContainsAny(k, "*?[") {
			continue
		}
		out = append(out, kv{k, normValue(v)})
	}
	return out
}

// sysctlFiles lists the files systemd-sysctl applies, in its order: by file
// name across the directories, a name in an earlier directory masking the
// same name in later ones, then /etc/sysctl.conf. x-ui's own files are left
// out.
func (e *Env) sysctlFiles() []string {
	byName := map[string]string{}
	for _, d := range sysctlDirs {
		for _, f := range e.glob(d + "/*.conf") {
			n := path.Base(f)
			if _, ok := byName[n]; !ok {
				byName[n] = f
			}
		}
	}
	names := make([]string, 0, len(byName))
	for n := range byName {
		names = append(names, n)
	}
	sort.Strings(names)
	var out []string
	for _, n := range names {
		f := byName[n]
		if f == SysctlFile || f == LegacyBBRFile || (f == OldSysctlFile && e.isOurs(f)) {
			continue
		}
		if e.resolve(f) == "/dev/null" {
			continue // masked
		}
		out = append(out, f)
	}
	if e.exists("/etc/sysctl.conf") {
		out = append(out, "/etc/sysctl.conf")
	}
	return out
}

// othersSettings is, for every key, the value the boot sequence would leave
// without x-ui's files.
func (e *Env) othersSettings() map[string]Setting {
	out := map[string]Setting{}
	for _, f := range e.sysctlFiles() {
		data, err := e.read(e.resolve(f))
		if err != nil {
			continue
		}
		for _, a := range parseSysctl(data) {
			out[a.Key] = Setting{Value: a.Value, File: f}
		}
	}
	return out
}

// adminOwned says whether a sysctl file is an admin's choice (x-ui keeps its
// choices) rather than a distribution default (x-ui may override it).
func (e *Env) adminOwned(file string) bool {
	if file == "/etc/sysctl.conf" || e.resolve(file) == "/etc/sysctl.conf" {
		return true
	}
	if strings.HasPrefix(file, "/usr/lib/") || strings.HasPrefix(file, "/lib/") {
		return false
	}
	return !e.pkgOwned(file)
}

func (e *Env) pkgOwned(file string) bool {
	if e.PkgOwned != nil {
		return e.PkgOwned(file)
	}
	if v, ok := e.owned[file]; ok {
		return v
	}
	v := e.queryOwner(file)
	if e.owned == nil {
		e.owned = map[string]bool{}
	}
	e.owned[file] = v
	return v
}

func (e *Env) queryOwner(file string) bool {
	for _, q := range [][]string{
		{"dpkg-query", "-S", file},
		{"rpm", "-qf", file},
		{"pacman", "-Qo", file},
		{"apk", "info", "-W", file},
	} {
		if !e.have(q[0]) {
			continue
		}
		out, err := e.Run(10*time.Second, q[0], q[1:]...)
		if err != nil {
			return false
		}
		if q[0] == "apk" {
			return strings.Contains(out, "is owned by")
		}
		return true
	}
	return false
}

// modprobeHashsize is the largest nf_conntrack hashsize set by another
// modprobe.d file, and that file.
func (e *Env) modprobeHashsize() (int64, string) {
	var best int64
	var file string
	seen := map[string]bool{}
	for _, d := range []string{"/etc/modprobe.d", "/run/modprobe.d", "/usr/local/lib/modprobe.d", "/usr/lib/modprobe.d", "/lib/modprobe.d"} {
		for _, f := range e.glob(d + "/*.conf") {
			if f == ModprobeFile || seen[path.Base(f)] {
				continue
			}
			seen[path.Base(f)] = true
			for _, l := range strings.Split(e.readTrim(f), "\n") {
				fs := strings.Fields(l)
				if len(fs) < 3 || fs[0] != "options" || fs[1] != "nf_conntrack" {
					continue
				}
				for _, o := range fs[2:] {
					if v, ok := strings.CutPrefix(o, "hashsize="); ok {
						if n := atoi64(v); n > best {
							best, file = n, f
						}
					}
				}
			}
		}
	}
	return best, file
}
